        internal EncounterPackInfo(bool isLeftovers) : base(isLeftovers) { }
        internal EncounterPackInfo(CardTemple temple) : base(temple)
        {
            // This is a cheat for the scrybe mods to allow the base game packs
            // to actually be defined the way the scrybe mods want
            if (temple == CardTemple.Tech)
                ModPrefix = "P03KCM";
            // TODO: Add similar hacks for grimora and magnificus
        }
        internal EncounterPackInfo(string cardPrefix, PackInfo.PackMetacategory category)
        {
            this.ModPrefix = cardPrefix;
            this.ValidFor = new() { category };
        }

        internal EncounterPackInfo(string cardPrefix)
        {
            this.ModPrefix = cardPrefix;
            string firstKey = this.PackContents.FirstOrDefault();
            if (string.IsNullOrEmpty(firstKey))
            {
                this.ValidFor = new() { PackInfo.PackMetacategory.LeshyPack };
            }
            else
            {
                var ebd = EncounterManager.AllEncountersCopy.FirstOrDefault(e => e.name.Equals(firstKey, StringComparison.InvariantCultureIgnoreCase));
                if (ebd == null)
                {
                    this.ValidFor = new() { PackInfo.PackMetacategory.LeshyPack };
                }
                else
                {
                    this.ValidFor = new() { PackInfo.GetTempleDefaultMetacategory(GetTemplesFromEncounter(ebd).First()) };
                }
            }
        }

        protected override void TryInitializeImpl()
        {
            List<string> encounters = Encounters.Select(e => e.name).ToList();
            List<string> regions = Regions.Select(e => e.name).ToList();
            if (encounters != null && encounters.Count > 0)
            {
                // Build the description
                AutoGeneratedDescription = $"Contains {encounters.Count} encounters.";

                // Build the title
                if (!String.IsNullOrEmpty(this.ModPrefix))
                {
                    try
                    {
                        PackInfo cardPack = PackManager.GetPackInfo(this.ModPrefix);
                        AutoGeneratedDescription = $"Contains {encounters.Count} encounters from {cardPack.Title}.";
                        AutoGeneratedTitle = $"Encounters Pack: {cardPack.Title}";
                        return;
                    }
                    catch { }
                }
                AutoGeneratedTitle = $"Encounters Pack: {this.ModPrefix}";
            }
        }

